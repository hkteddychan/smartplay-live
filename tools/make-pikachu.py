"""Generate a 24x24 Pikachu pixel art header for the SOCKS5 status screen.

Creates:
  firmware/esp32_socks5_proxy/pikachu.h  (2 animation frames + grey offline version)
  docs/pikachu-preview.png

Colors are RGB565. Art is drawn programmatically (ellipses + triangles +
circles) so it is trivially tweakable.
"""
from __future__ import annotations

import os

from PIL import Image
from PIL import ImageDraw

W = H = 24

PALETTE = {
    "Y": (0xFF, 0xD3, 0x4E),   # pikachu 黄
    "K": (0x10, 0x10, 0x10),   # 輪廓/耳尖/眼
    "R": (0xE8, 0x48, 0x3F),   # 腮邊
    "W": (0xFF, 0xFF, 0xFF),   # 眼高光
    ".": None,                  # 背景（屏幕上就係黑）
}


def rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


GRID_GREY: dict[str, tuple[int, int, int]] = {
    "Y": (0x5A, 0x5A, 0x62),   # 灰黄 -> 暗灰
    "K": (0x0C, 0x0C, 0x0C),
    "R": (0x40, 0x40, 0x46),   # 紅腮 -> 深灰
    "W": (0x9B, 0x9B, 0xA0),
    ".": None,
}


def inside_head(x: float, y: float) -> bool:
    return ((x - 11.5) / 10.2) ** 2 + ((y - 10.0) / 6.2) ** 2 <= 1.0


def inside_body(x: float, y: float) -> bool:
    return ((x - 11.5) / 7.4) ** 2 + ((y - 18.5) / 5.0) ** 2 <= 1.0


def tri(p0, p1, p2, x, y) -> bool:
    def sign(ax, ay, bx, by, cx, cy):
        return (bx - ax) * (cy - ay) - (by - ay) * (cx - ax)
    d1 = sign(x, y, *p0, *p1)
    d2 = sign(x, y, *p1, *p2)
    d3 = sign(x, y, *p2, *p0)
    neg = (d1 < 0) or (d2 < 0) or (d3 < 0)
    pos = (d1 > 0) or (d2 > 0) or (d3 > 0)
    return not (neg and pos)


def build_frame(ear_shift: int, mouth_open: bool) -> list[list[str]]:
    """ear_shift: -1/0/1 -> 耳朵輕微擺動；mouth_open: 第二幀開口。"""
    g = [["." for _ in range(W)] for _ in range(H)]

    # 身體（先畫，令頭壓面）
    for y in range(H):
        for x in range(W):
            if inside_body(x, y):
                g[y][x] = "Y"

    # 耳朵（三角）：尖 proxy 輕微 shift 做動畫
    lt = (6 + ear_shift, 1)
    l_ear = (lt, (10, 7), (2, 7))
    r_ear = ((17 + ear_shift, 1), (21, 7), (13, 7))
    for y in range(H):
        for x in range(W):
            for tri_pts in (l_ear, r_ear):
                if tri(*tri_pts, x, y):
                    g[y][x] = "K" if y <= 2 else "Y"    # 黑耳尖

    # 頭
    for y in range(4, 17):
        for x in range(W):
            if inside_head(x, y):
                g[y][x] = "Y"

    # 眼（2x2 黑 + 高光）
    for ex in (8, 14):
        for dy in range(2):
            for dx in range(2):
                g[8 + dy][ex + dx] = "K"
        g[8][ex] = "W"

    # 腮邊（紅圓 r=2）
    for cx in (6.0, 17.0):
        for y in range(10, 14):
            for x in range(4, 21):
                if (x - cx) ** 2 + (y - 11.5) ** 2 <= 2.6:
                    g[y][x] = "R"

    # 口
    if mouth_open:
        for y in range(12, 15):
            for x in range(10, 14):
                if (x in (10, 13) and y in (12, 13)) or \
                   (x in (11, 12) and y in (13, 14)):
                    g[y][x] = "K"
    else:
        g[12][10] = "K"; g[12][13] = "K"
        g[13][11] = "K"; g[13][12] = "K"

    # 小手（身兩側）
    for y in range(17, 20):
        g[y][4] = "Y"; g[y][19] = "Y"
    g[20][4] = "Y"; g[20][19] = "Y"

    # 小腳
    for x in range(7, 11):
        g[22][x] = "Y"; g[23][x] = "Y"
    for x in range(13, 17):
        g[22][x] = "Y"; g[23][x] = "Y"

    return g


def to_array(g: list[list[str]], palette: dict) -> list[int]:
    out = []
    for row in g:
        for cell in row:
            rgb = palette[cell]
            out.append(0x0000 if rgb is None else rgb565(*rgb))  # 背景=0，固件可以跳過
    return out


def flat(arr: list[int]) -> str:
    return ", ".join(f"0x{v:04X}" for v in arr)


def write_header(frames: list[list[int]], grey: list[int]) -> None:
    lines = [
        "// Auto-generated by tools/make-pikachu.py — do not edit.",
        f"// {W}x{H} pikachu pixel art: 2 anim frames + offline grey version.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define PIK_W {W}",
        f"#define PIK_H {H}",
        f"#define PIK_PIX {W * H}",
        "",
    ]
    lines += [f"static const uint16_t pik_f1[PIK_PIX] = {{\n{flat(frames[0])}}};"]
    lines += [f"static const uint16_t pik_f2[PIK_PIX] = {{\n{flat(frames[1])}}};"]
    lines += [f"static const uint16_t pik_grey[PIK_PIX] = {{\n{flat(grey)}}};"]

    out = os.path.join("firmware", "esp32_socks5_proxy", "pikachu.h")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"header  : {out} ({os.path.getsize(out)/1024:.1f} KB)")


def preview(g1, g2, grey) -> None:
    scale = 10
    img = Image.new("RGB", ((W * scale + 20) * 3, H * scale + 40), (18, 18, 22))
    d = ImageDraw.Draw(img)

    for idx, (art, label) in enumerate(
        [(g1, "frame 1"), (g2, "frame 2"), (grey, "offline grey")]):
        ox = idx * (W * scale + 20) + 10

        for y, row in enumerate(art):
            for x, cell in enumerate(row):
                rgb = (GRID_GREY if idx == 2 else PALETTE)[cell]
                if rgb is None:
                    rgb = (10, 10, 14)
                d.rectangle([ox + x * scale, y * scale,
                             ox + x * scale + scale - 1, y * scale + scale - 1],
                            fill=rgb)
        d.text((ox + 40, H * scale + 10), label, fill=(255, 255, 255))

    img.save(os.path.join("docs", "pikachu-preview.png"))
    print("preview : docs/pikachu-preview.png")


def main() -> None:
    f1 = build_frame(0, False)
    f2 = build_frame(1, True)     # 耳仔擺 + 開口 = 活潑兩幀
    grey = build_frame(0, False)
    write_header([to_array(f1, PALETTE), to_array(f2, PALETTE)],
                 to_array(grey, GRID_GREY))
    preview(f1, f2, grey)


if __name__ == "__main__":
    main()
