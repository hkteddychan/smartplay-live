"""
Generate a 16x16 1-bit CJK bitmap font for the CYD chat firmware.

Charset: Big5 symbols + Level 1 (the ~5,400 most common Traditional Chinese
characters) + a few extras. ASCII is left to TFT_eSPI's built-in font 2.

Outputs:
  firmware/esp32_cyd_chat/cjk_font.h
  docs/cjk-chat-preview.png   (mock of the real chat screen)

Usage:
  python tools/make-cjk-font.py
"""
from __future__ import annotations

import os

from PIL import Image, ImageDraw, ImageFont

CELL = 16
FONT_PATH = r"C:\Windows\Fonts\msjh.ttc"
FONT_INDEX = 0
OUT_HEADER = os.path.join("firmware", "esp32_cyd_chat", "cjk_font.h")
OUT_PREVIEW = os.path.join("docs", "cjk-chat-preview.png")

# A few characters the AI is likely to need that may sit outside Big5 L1
EXTRA = "π°²³≠≤≥→←∞√∑∫≈±×÷·…—「」『』"


def build_charset() -> list[int]:
    cps: set[int] = set()

    # Big5: A140-A3BF symbols/fullwidth, A440-C67E level-1 hanzi
    for hi in range(0xA1, 0xC7):
        for lo in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
            try:
                ch = bytes([hi, lo]).decode("big5")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1:
                cps.add(ord(ch))

    for ch in EXTRA:
        cps.add(ord(ch))

    return sorted(c for c in cps if c > 0x7F and c <= 0xFFFF)


def render_glyph(font: ImageFont.FreeTypeFont, cp: int) -> bytes:
    img = Image.new("1", (CELL, CELL), 0)
    d = ImageDraw.Draw(img)
    ch = chr(cp)
    bbox = d.textbbox((0, 0), ch, font=font, anchor="lt")
    # nudge vertically so the ink sits inside the cell
    dy = 0
    if bbox[3] > CELL:
        dy = CELL - bbox[3]
    if bbox[1] + dy < 0:
        dy = -bbox[1]
    d.text((0, dy), ch, font=font, fill=1, anchor="lt")

    out = bytearray()
    px = img.load()
    for y in range(CELL):
        hi = lo = 0
        for x in range(CELL):
            if px[x, y]:
                if x < 8:
                    hi |= 1 << (7 - x)
                else:
                    lo |= 1 << (15 - x)
        out.append(hi)
        out.append(lo)
    return bytes(out)


def write_header(cps: list[int], bits: list[bytes]) -> None:
    lines = [
        "// Auto-generated by tools/make-cjk-font.py — do not edit.",
        f"// {len(cps)} glyphs, {CELL}x{CELL} 1-bit, MSB-first, 2 bytes per row.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define CJK_GLYPH_W {CELL}",
        f"#define CJK_GLYPH_H {CELL}",
        f"#define CJK_GLYPH_BYTES {CELL * 2}",
        f"#define CJK_COUNT {len(cps)}u",
        "",
        "static const uint16_t cjk_cp[CJK_COUNT] = {",
    ]
    for i in range(0, len(cps), 12):
        chunk = ", ".join(f"0x{c:04X}" for c in cps[i : i + 12])
        lines.append("  " + chunk + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const uint8_t cjk_bits[CJK_COUNT * CJK_GLYPH_BYTES] = {")
    for g in bits:
        lines.append("  " + ",".join(f"0x{b:02X}" for b in g) + ",")
    lines.append("};")
    lines.append("")

    with open(OUT_HEADER, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def draw_cjk_line(d, text, x, y, font):
    for ch in text:
        cp = ord(ch)
        if cp < 0x80:
            d.text((x, y + 4), ch, font=font, fill=(255, 255, 255), anchor="lt")
            x += 8
        else:
            d.text((x, y), ch, font=font, fill=(255, 255, 255), anchor="lt")
            x += CELL


def char_w(ch: str) -> int:
    return 8 if ord(ch) < 0x80 else CELL


def wrap_cjk(text: str, maxw: int) -> list[str]:
    lines, cur, w = [], "", 0
    for ch in text:
        cw = char_w(ch)
        if w + cw > maxw and cur:
            lines.append(cur)
            cur, w = "", 0
        cur += ch
        w += cw
    if cur:
        lines.append(cur)
    return lines or [""]


def make_preview() -> None:
    font = ImageFont.truetype(FONT_PATH, CELL, index=FONT_INDEX)

    W, H = 320, 240
    img = Image.new("RGB", (W, H), (8, 12, 16))
    d = ImageDraw.Draw(img)

    # header
    d.rectangle([0, 0, W, 27], fill=(24, 28, 32))
    d.text((8, 6), "Gemma 4 31B", font=font, fill=(255, 255, 255))
    d.text((104, 6), "14:05", font=font, fill=(255, 255, 255))
    d.text((150, 7), "Sat 31 Oct", font=font, fill=(132, 132, 132))

    # user bubble (right)
    user_lines = wrap_cjk("證明勾股定理，並說明前提", 250)
    uh = len(user_lines) * 18 + 14
    uy = 34
    d.rounded_rectangle([296 - 264, uy, 296, uy + uh], radius=8, fill=(2, 6, 30))
    for i, ln in enumerate(user_lines):
        draw_cjk_line(d, ln, 40, uy + 7 + i * 18, font)

    # ai bubble (left)
    ai_text = ("餘弦定理：c^2 = a^2 + b^2 - 2ab cosC。當 C = 90 度時 cosC = 0，"
               "所以 c^2 = a^2 + b^2。若不是直角，cosC 不為零，多出的項不能省略。")
    ai_lines = wrap_cjk(ai_text, 244)
    ah = len(ai_lines) * 18 + 14
    ay = uy + uh + 8
    d.rounded_rectangle([32, ay, 296, ay + ah], radius=8, fill=(48, 50, 54))
    for i, ln in enumerate(ai_lines):
        draw_cjk_line(d, ln, 40, ay + 7 + i * 18, font)

    # quick bar
    qy = 178
    labels = ["ALG", "CALC", "PHYS", "OPT", "PROOF"]
    for i, lb in enumerate(labels):
        bx = 4 + i * 63
        d.rounded_rectangle([bx, qy + 2, bx + 59, qy + 22], radius=6, fill=(41, 69, 45))
        d.text((bx + 14, qy + 6), lb, font=font, fill=(0, 255, 0))

    # input bar
    d.rectangle([0, 204, W, H], fill=(24, 28, 32))
    d.rounded_rectangle([8, 209, W - 82, 231], radius=8, fill=(0, 0, 0))
    draw_cjk_line(d, "輸入問題…", 16, 210, font)

    img = img.resize((W * 2, H * 2), Image.NEAREST)
    img.save(OUT_PREVIEW)
    print(f"saved {OUT_PREVIEW}")


def main() -> None:
    cps = build_charset()
    font = ImageFont.truetype(FONT_PATH, CELL, index=FONT_INDEX)

    bits = [render_glyph(font, cp) for cp in cps]
    write_header(cps, bits)

    glyph_bytes = len(cps) * CELL * 2
    index_bytes = len(cps) * 2
    print(f"glyphs      : {len(cps)}")
    print(f"bitmap bytes: {glyph_bytes} ({glyph_bytes/1024:.1f} KB)")
    print(f"index bytes : {index_bytes} ({index_bytes/1024:.1f} KB)")
    print(f"total flash : {(glyph_bytes+index_bytes)/1024:.1f} KB")
    print(f"header      : {OUT_HEADER} ({os.path.getsize(OUT_HEADER)/1024:.0f} KB)")

    make_preview()


if __name__ == "__main__":
    main()
