    "上次更新下次檢查"
    "已連接連線中斷線"
    "無符合條件"
    "羽毛球場籃球場排球場網球場足球場"
    "場地時間分區"
    "共收到通知"
    "目前未有新時段"
    "…"
    # v3.0 放場通知器介面用字
    "放場通知器等待放場中"
    "晚上點後餘額增加或新時段"
    "已連線未連線只用失敗"
